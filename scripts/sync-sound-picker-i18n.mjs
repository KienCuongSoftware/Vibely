function patchLocale(code, strings) {
  const file = path.join(I18N_DIR, `${code}.json`)
  if (!fs.existsSync(file)) {
    console.warn(`skip missing ${code}.json`)
    return
  }
  const data = JSON.parse(fs.readFileSync(file, 'utf8'))
  const photo = data?.upload?.photo
  if (!photo) {
    console.warn(`skip ${code}: no upload.photo`)
    return
  }
  photo.changeSound = strings.changeSound
  photo.removeSound = strings.removeSound
  photo.soundPicker = strings.soundPicker
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`)
  console.log(`patched ${code}.json`)
}

const files = fs.readdirSync(I18N_DIR).filter((f) => f.endsWith('.json'))
for (const file of files) {
  const code = file.replace(/\.json$/, '')
  const strings = T[code] || T.en
  patchLocale(code, strings)
}

console.log('done')
